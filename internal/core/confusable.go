	m['ŵ'] = 'w' // 拉丁小写 w 带抑扬符

	// === X 系列（x, х, Х, χ） ===
	m['Ｘ'] = 'x'
	m['ｘ'] = 'x'
	m['х'] = 'x' // 西里尔字母 х（U+0445，视觉上等同于 x）
	m['Х'] = 'x' // 西里尔大写字母 Х（U+0425）
	m['χ'] = 'x' // 希腊字母 chi

	// === Y 系列（y, ý, ÿ, ŷ, у, ψ） ===
	m['Ｙ'] = 'y'
	m['ｙ'] = 'y'
	m['у'] = 'y' // 西里尔字母 у（U+0443，视觉上等同于 y）
	m['ý'] = 'y' // 拉丁小写 y 带锐音符
	m['ÿ'] = 'y' // 拉丁小写 y 带分音符
	m['ŷ'] = 'y' // 拉丁小写 y 带抑扬符
