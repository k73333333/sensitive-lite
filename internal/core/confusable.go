	m['ġ'] = 'g' // 拉丁小写 g 带上点符
	m['ǧ'] = 'g' // 拉丁小写 g 带抑扬符

	// === H 系列（h, ĥ, ħ, н, η） ===
	m['Ｈ'] = 'h'
	m['ｈ'] = 'h'
	m['н'] = 'h' // 西里尔字母 н（U+043D，视觉上等同于 h）
	m['ĥ'] = 'h' // 拉丁小写 h 带抑扬符
	m['ħ'] = 'h' // 拉丁小写 h 带横线
	m['η'] = 'h' // 希腊字母 eta（小写 η 视觉接近 h）

	// === I 系列（i, í, ì, î, ï, ī, ĭ, į, ı, і, ι） ===
	m['Ｉ'] = 'i'
	m['ｉ'] = 'i'
	m['í'] = 'i'
	m['ì'] = 'i'
	m['î'] = 'i'
	m['ï'] = 'i'
	m['і'] = 'i' // 西里尔字母 і
	m['ι'] = 'i' // 希腊字母 iota
	m['ī'] = 'i' // 拉丁小写 i 带长音符
	m['ĭ'] = 'i' // 拉丁小写 i 带短音符
	m['į'] = 'i' // 拉丁小写 i 带反尾形符
	m['ı'] = 'i' // 拉丁小写无点 i
	m['ĩ'] = 'i' // 拉丁小写 i 带颚化符

	// === J 系列 ===
	m['Ｊ'] = 'j'
	m['ｊ'] = 'j'
	m['ĵ'] = 'j' // 拉丁小写 j 带抑扬符

	// === K 系列（k, ķ, ĸ, κ, к） ===
	m['Ｋ'] = 'k'
	m['ｋ'] = 'k'
	m['к'] = 'k' // 西里尔字母 к（U+043A，视觉上等同于 k）
	m['κ'] = 'k' // 希腊字母 kappa
	m['ķ'] = 'k' // 拉丁小写 k 带变音符
	m['ĸ'] = 'k' // 拉丁小写 kra

	// === L 系列（l, ĺ, ļ, ľ, ŀ, ł, λ） ===
	m['Ｌ'] = 'l'
	m['ｌ'] = 'l'
	m['λ'] = 'l' // 希腊字母 lambda（视觉上类似小写 l）
	m['ĺ'] = 'l' // 拉丁小写 l 带锐音符
	m['ļ'] = 'l' // 拉丁小写 l 带变音符
	m['ľ'] = 'l' // 拉丁小写 l 带抑扬符
	m['ŀ'] = 'l' // 拉丁小写 l 带中间点
	m['ł'] = 'l' // 拉丁小写 l 带横线

	// === M 系列（m, м, μ） ===
	m['Ｍ'] = 'm'
	m['ｍ'] = 'm'
	m['м'] = 'm' // 西里尔字母 м（U+043C，视觉上等同于 m）
	m['μ'] = 'm' // 希腊字母 mu（视觉上类似 m 的一竖）

	// === N 系列（n, ñ, ń, ň, ņ, ŋ, η, π） ===
	m['Ｎ'] = 'n'
	m['ｎ'] = 'n'
	m['ñ'] = 'n'
	m['ń'] = 'n' // 拉丁小写 n 带锐音符
	m['ň'] = 'n' // 拉丁小写 n 带抑扬符
	m['ņ'] = 'n' // 拉丁小写 n 带变音符
	m['ŋ'] = 'n' // 拉丁小写 eng → n
	m['π'] = 'n' // 希腊字母 pi（视觉上类似小写 n）

	// === O 系列（o, ó, ò, ô, ö, õ, ō, ŏ, ő, ø, о, ο） ===
	m['Ｏ'] = 'o' // 全角大写 O → 半角小写 o
	m['ｏ'] = 'o' // 全角小写 o
	m['ó'] = 'o'
	m['ò'] = 'o'
	m['ô'] = 'o'
	m['ö'] = 'o'
	m['о'] = 'o' // 西里尔字母 о
	m['ο'] = 'o' // 希腊字母 omicron
	m['õ'] = 'o' // 拉丁小写 o 带颚化符
	m['ō'] = 'o' // 拉丁小写 o 带长音符
	m['ŏ'] = 'o' // 拉丁小写 o 带短音符
	m['ő'] = 'o' // 拉丁小写 o 带双重音符
	m['ø'] = 'o' // 拉丁小写 o 带斜线
	m['ơ'] = 'o' // 拉丁小写 o 带角符

	// === P 系列（p, р, ρ） ===
	m['Ｐ'] = 'p'
	m['ｐ'] = 'p'
	m['р'] = 'p' // 西里尔字母 р（U+0440，视觉上等同于 p）
	m['ρ'] = 'p' // 希腊字母 rho（小写 ρ 视觉接近 p）
	m['þ'] = 'p' // 拉丁小写 thorn → p（冰岛语þ视觉接近p）

	// === Q 系列 ===
	m['Ｑ'] = 'q'
	m['ｑ'] = 'q'
	m['θ'] = 'q' // 希腊字母 theta（视觉上类似 q）

	// === R 系列（r, ŕ, ř, ŗ, г） ===
	m['Ｒ'] = 'r'
	m['ｒ'] = 'r'
	m['г'] = 'r' // 西里尔字母 г（U+0433，视觉上等同于 r）
	m['ŕ'] = 'r' // 拉丁小写 r 带锐音符
	m['ř'] = 'r' // 拉丁小写 r 带抑扬符

	// === S 系列（s, ś, ŝ, ş, š, ș, ʂ, ß, σ, ς） ===
	m['Ｓ'] = 's'
	m['ｓ'] = 's'
	m['σ'] = 's' // 希腊字母 sigma
	m['ς'] = 's' // 希腊字母 final sigma
	m['ś'] = 's' // 拉丁小写 s 带锐音符
	m['ŝ'] = 's' // 拉丁小写 s 带抑扬符
	m['ş'] = 's' // 拉丁小写 s 带变音符
	m['š'] = 's' // 拉丁小写 s 带抑扬符
	m['ș'] = 's' // 拉丁小写 s 带逗号
	m['ʂ'] = 's' // 拉丁小写 s 带钩
	m['ß'] = 's' // 德语 scharfes S → s

	// === T 系列（t, ţ, ť, ŧ, т, τ） ===
	m['Ｔ'] = 't'
	m['ｔ'] = 't'
	m['т'] = 't' // 西里尔字母 т（U+0442，视觉上等同于 t）
	m['τ'] = 't' // 希腊字母 tau
	m['ţ'] = 't' // 拉丁小写 t 带变音符
	m['ť'] = 't' // 拉丁小写 t 带抑扬符
	m['ŧ'] = 't' // 拉丁小写 t 带横线

	// === U 系列（u, ú, ù, û, ü, ũ, ū, ŭ, ů, ű, υ） ===
	m['Ｕ'] = 'u'
	m['ｕ'] = 'u'
	m['ú'] = 'u'
	m['ù'] = 'u'
	m['û'] = 'u'
	m['ü'] = 'u'
	m['υ'] = 'u' // 希腊字母 upsilon（小写 υ 视觉接近 u）
	m['ũ'] = 'u' // 拉丁小写 u 带颚化符
	m['ū'] = 'u' // 拉丁小写 u 带长音符
	m['ŭ'] = 'u' // 拉丁小写 u 带短音符
	m['ů'] = 'u' // 拉丁小写 u 带圆圈
	m['ű'] = 'u' // 拉丁小写 u 带双重音符
