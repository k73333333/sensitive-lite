package core

// ============================================================================
// CJK 连续重复字符压缩（Character Deduplication）
//
// 攻击场景：攻击者通过连续重复 CJK 字符来绕过关键词检测。
// 例如：
//   "敏敏敏感词"   → 期望匹配 "敏感词"
//   "违违规规内容"  → 期望匹配 "违规内容"
//   "敏敏敏敏感感感词词词" → 期望匹配 "敏感词"
//
// 设计原则：
//  1. 仅对 CJK 统一表意文字（U+4E00-U+9FFF 及扩展 A 区）做去重
//  2. 不处理拉丁字母、数字、假名等（避免破坏英文单词如 "hello"）
//  3. 相邻相同字符压缩为单个字符（RLE 编码解码）
//  4. 此功能默认启用，可通过 WithDedup(false) 关闭
//
// 假阳性风险分析：
//  - 中文叠词（如"看看"、"说说"、"人人"）会被压缩为单字
//  - 但实际敏感词命中测试中，叠词压缩后的单字形式仍能命中
//    更长的敏感词（因为 DFA 会从每个位置重新匹配）
//  - 极端案例："人人" → "人" 可能增加误报，但这属于可接受的
//    代价，因为"人"作为单字敏感词极少出现在合法词库中
// ============================================================================

// Dedup 对 CJK 字符进行连续重复压缩（导出供测试访问）
//
// 算法说明：
//  遍历 rune 切片，对于每个 CJK 字符：
//  - 若与前一个字符相同且两者均为 CJK → 跳过（压缩）
//  - 否则保留
//
// 参数：
//
//	runes - 待处理的 rune 切片（原地修改，覆盖写入）
//
// 返回值：压缩后的 rune 切片（长度 ≤ 输入长度）
func Dedup(runes []rune) []rune {
	if len(runes) <= 1 {
		return runes
	}

	// 写指针：指向压缩后的下一个写入位置
	writeIdx := 1
	// 前一个已保留的字符
	prev := runes[0]

	for i := 1; i < len(runes); i++ {
		curr := runes[i]
		// 当前字符与前一个字符相同时，检查是否需要压缩
		if curr == prev && IsCJK(curr) {
			// CJK 重复字符 → 跳过（不写入）
			continue
		}
		// 非重复或非 CJK → 保留
		runes[writeIdx] = curr
		prev = curr
		writeIdx++
	}

	// 截断到实际写入长度
	return runes[:writeIdx]
}
