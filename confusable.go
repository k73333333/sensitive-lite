package sensitive

// ============================================================================
// 形近字 / 同音字映射表
//
// 设计原则：
//  1. 仅从非标准/干扰字符 → 标准字符做单向映射
//  2. 不对标准字符之间做相互映射（避免破坏合法文本）
//  3. 数字/字母的 leet speak 混淆需要通过词库扩展或运行时变体生成来处理
//
// 中国互联网常见的文本干扰手段：
//  1. 偏旁部首替换（亻→人、讠→言、氵→水、扌→手…）
//  2. 形近字替换（日→曰、己→已→巳、未→末…）
//  3. 同音字替换（可→克、在→再、的→嘚…）
//  4. 全角/特殊数字符号 → 半角数字（Ｏ→0、〇→0…）
//  5. 繁体字 → 简体字映射
//
// 注意：此映射表为基础映射，用户可通过敏感词库补充变体词汇
// 来覆盖更复杂的业务场景（如数字/字母 leet speak 混淆）
// ============================================================================

// buildConfusableMap 构建形近字/同音字映射表
// 返回：干扰字符 → 标准字符的单向映射
