	m['₀'] = '0'  // 下标 0
	m['⓪'] = '0'  // 带圈数字 0
	m['０'] = '0'  // 全角数字 0
	m['º'] = '0'  // 阳性序数符号

	m['１'] = '1'  // 全角数字 1
	m['₁'] = '1'  // 下标 1
	m['①'] = '1'  // 带圈数字 1

	m['２'] = '2'  // 全角数字 2
	m['₂'] = '2'  // 下标 2
	m['②'] = '2'  // 带圈数字 2

	m['３'] = '3'  // 全角数字 3
	m['₃'] = '3'  // 下标 3
	m['③'] = '3'  // 带圈数字 3

	m['４'] = '4'  // 全角数字 4
	m['₄'] = '4'  // 下标 4
	m['④'] = '4'  // 带圈数字 4

	m['５'] = '5'  // 全角数字 5
	m['₅'] = '5'  // 下标 5
	m['⑤'] = '5'  // 带圈数字 5

	m['６'] = '6'  // 全角数字 6
	m['₆'] = '6'  // 下标 6
	m['⑥'] = '6'  // 带圈数字 6

	m['７'] = '7'  // 全角数字 7
	m['₇'] = '7'  // 下标 7
	m['⑦'] = '7'  // 带圈数字 7

	m['８'] = '8'  // 全角数字 8
	m['₈'] = '8'  // 下标 8
	m['⑧'] = '8'  // 带圈数字 8

	m['９'] = '9'  // 全角数字 9
	m['₉'] = '9'  // 下标 9
	m['⑨'] = '9'  // 带圈数字 9

	// --- 全角/特殊拉丁字母 → 半角拉丁字母 ---
	// 仅映射全角拉丁字母和特殊 Unicode 变体，不映射标准 ASCII 字母
	m['Ａ'] = 'a'
	m['ａ'] = 'a'
	m['α'] = 'a'  // 希腊字母 alpha → a
	m['а'] = 'a'  // 西里尔字母 а（U+0430，视觉上等同于 a）
	m['＠'] = 'a' // 全角 @

	m['Ｂ'] = 'b'
	m['ｂ'] = 'b'

	m['Ｃ'] = 'c'
	m['ｃ'] = 'c'
	m['ϲ'] = 'c' // 希腊字母 lunate sigma

	m['Ｄ'] = 'd'
	m['ｄ'] = 'd'

	m['Ｅ'] = 'e'
	m['ｅ'] = 'e'
	m['е'] = 'e' // 西里尔字母 е
	m['é'] = 'e'
	m['è'] = 'e'
	m['ê'] = 'e'
	m['ë'] = 'e'

	m['Ｆ'] = 'f'
	m['ｆ'] = 'f'

	m['Ｇ'] = 'g'
	m['ｇ'] = 'g'

	m['Ｈ'] = 'h'
	m['ｈ'] = 'h'

	m['Ｉ'] = 'i'
	m['ｉ'] = 'i'
	m['í'] = 'i'
	m['ì'] = 'i'
	m['î'] = 'i'
	m['ï'] = 'i'
	m['і'] = 'i' // 西里尔字母 і

	m['Ｊ'] = 'j'
	m['ｊ'] = 'j'

	m['Ｋ'] = 'k'
	m['ｋ'] = 'k'

	m['Ｌ'] = 'l'
	m['ｌ'] = 'l'

	m['Ｍ'] = 'm'
	m['ｍ'] = 'm'

	m['Ｎ'] = 'n'
	m['ｎ'] = 'n'
	m['ñ'] = 'n'

	m['Ｏ'] = 'o'   // 全角大写 O → 半角小写 o
	m['ｏ'] = 'o'  // 全角小写 o
	m['ó'] = 'o'
	m['ò'] = 'o'
	m['ô'] = 'o'
	m['ö'] = 'o'
	m['о'] = 'o' // 西里尔字母 о
	m['ο'] = 'o' // 希腊字母 omicron

	m['Ｐ'] = 'p'
	m['ｐ'] = 'p'

	m['Ｑ'] = 'q'
	m['ｑ'] = 'q'

	m['Ｒ'] = 'r'
	m['ｒ'] = 'r'

	m['Ｓ'] = 's'
	m['ｓ'] = 's'
	m['＄'] = 's' // 全角 $

	m['Ｔ'] = 't'
	m['ｔ'] = 't'

	m['Ｕ'] = 'u'
	m['ｕ'] = 'u'
	m['ú'] = 'u'
	m['ù'] = 'u'
	m['û'] = 'u'
	m['ü'] = 'u'

	m['Ｖ'] = 'v'
	m['ｖ'] = 'v'

	m['Ｗ'] = 'w'
	m['ｗ'] = 'w'

	m['Ｘ'] = 'x'
	m['ｘ'] = 'x'

	m['Ｙ'] = 'y'
	m['ｙ'] = 'y'

	m['Ｚ'] = 'z'
	m['ｚ'] = 'z'

	// --- 中文偏旁部首替换 ---
	// 亻→ 人
	m['亻'] = '人'
	m['彳'] = '人'
	// 讠→ 言
	m['讠'] = '言'
	m['訁'] = '言'
	// 氵→ 水
	m['氵'] = '水'
	m['氺'] = '水'
	// 扌→ 手
	m['扌'] = '手'
	m['龵'] = '手'
	// 饣→ 食
	m['饣'] = '食'
	m['飠'] = '食'
	// 纟→ 丝
	m['纟'] = '丝'
	m['糹'] = '丝'
	// 钅→ 金
	m['钅'] = '金'
	m['釒'] = '金'
	// 贝→ 貝
	m['貝'] = '贝'
	// 车→ 車
	m['車'] = '车'
	// 马→ 馬
	m['馬'] = '马'
	// 鱼→ 魚
	m['魚'] = '鱼'
	// 鸟→ 鳥
	m['鳥'] = '鸟'
	// 门→ 門
	m['門'] = '门'
	// 页→ 頁
	m['頁'] = '页'
	// 见→ 見
	m['見'] = '见'
	// 长→ 長
	m['長'] = '长'
	// 风→ 風
	m['風'] = '风'
	// 飞→ 飛
	m['飛'] = '飞'
	// 韦→ 韋
	m['韋'] = '韦'

	// --- 中文形近字替换 ---
