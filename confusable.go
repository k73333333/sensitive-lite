	m['曰'] = '日'
	m['⽇'] = '日'
	// 己 → 已 → 巳
	m['已'] = '己'
	m['巳'] = '己'
	// 未 → 末
	m['末'] = '未'
	// 千 → 干 → 于
	m['干'] = '千'
	m['于'] = '千'
	// 土 → 士
	m['士'] = '土'
	// 大 → 太 → 犬
	m['太'] = '大'
	m['犬'] = '大'
	// 天 → 夫 → 夭
	m['夫'] = '天'
	m['夭'] = '天'
	// 人 → 入 → 八
	m['入'] = '人'
	// 刀 → 刁
	m['刁'] = '刀'
	// 王 → 玉 → 主
	m['玉'] = '王'
	m['主'] = '王'
	// 目 → 且
	m['且'] = '目'
	// 本 → 木
	m['木'] = '本'
	// 白 → 百 → 自
	m['百'] = '白'
	m['自'] = '白'
	// 皿 → 血
	m['血'] = '皿'
	// 冶 → 治
	m['治'] = '冶'
	// 酒 → 洒
	m['洒'] = '酒'
	// 免 → 兔
	m['兔'] = '免'
	// 候 → 侯
	m['侯'] = '候'
	// 准 → 淮
	m['淮'] = '准'
	// 晴 → 睛
	m['睛'] = '晴'
	// 勾 → 句
	m['句'] = '勾'
	// 余 → 佘
	m['佘'] = '余'
	// 子 → 孑 → 孓
	m['孑'] = '子'
	m['孓'] = '子'
	// 风 → 凤
	m['凤'] = '风'
	// 爪 → 瓜
	m['瓜'] = '爪'
	// 甲 → 由 → 申
	m['由'] = '甲'
	m['申'] = '甲'

	// --- 中文同音字替换（常用替代映射） ---
	m['克'] = '可'
	m['颗'] = '可'
	m['滴'] = '的'
	m['嘚'] = '的'
	m['德'] = '的'
	m['再'] = '在'
	m['辣'] = '啦'
	m['喇'] = '啦'
	m['辽'] = '了'
	m['灰'] = '会'
	m['汇'] = '会'
	m['舅'] = '就'
	m['森'] = '生'
	m['升'] = '生'
